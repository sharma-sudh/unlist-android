package com.sudh.unlist.util

import com.sudh.unlist.BuildConfig

object Constants {
    /** Backend base URL — see app/build.gradle.kts to change deployments. */
    const val BASE_URL: String = BuildConfig.BASE_URL

    /** Google OAuth Web Client ID used by Credential Manager to mint an ID token. */
    const val GOOGLE_WEB_CLIENT_ID: String = BuildConfig.GOOGLE_WEB_CLIENT_ID

    /**
     * Custom scheme, kept for one purpose only: it's what the backend's web fallback page
     * (render_report_page in applinks.py) uses for its "Open in Unlist app" button, via
     * intent://report/<id>#Intent;scheme=unlist;package=com.sudh.unlist;end — that's a direct,
     * unambiguous "launch this app" instruction that bypasses App Link verification entirely,
     * which is exactly what you want from a page the user is already looking at inside a browser.
     * It is NOT used for the links generated by Share anymore — see [deepLinkFor].
     */
    const val DEEP_LINK_SCHEME = "unlist"
    const val DEEP_LINK_HOST = "report"

    /**
     * Host for the real https:// App Link, matched against AndroidManifest.xml's autoVerify
     * intent-filter and against the domain assetlinks.json is served from (applinks.py on the
     * backend). Must stay in sync with all three by hand — there's no single source of truth
     * shared between the Android manifest and the backend's Python constant.
     */
    const val APP_LINK_HOST = "unlist-backend-s280.onrender.com"

    /**
     * Link produced by the Share action. Deliberately a real https:// URL now, not
     * unlist://report/<id> — see the commit that added App Links for why: a custom scheme
     * has no fallback for a recipient without the app installed, and isn't reliably tappable
     * in most share targets. This URL works for everyone: verified App Link opens the app
     * directly if installed (once Android's Digital Asset Links check passes — see the
     * SHA-256 fingerprint note in applinks.py), and the same URL renders a normal webpage
     * for anyone who doesn't have the app.
     */
    fun deepLinkFor(reportId: String) = "https://$APP_LINK_HOST/report/$reportId"

    const val COMPARE_MIN_URLS = 2
    const val COMPARE_MAX_URLS = 4
}
